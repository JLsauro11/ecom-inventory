<?php
// One row selection and quantity basis for the Current Stocks screen and download.
function cs_stock_rows($products,$search='',$status=''){
 $q=norm($search);$rows=[];
 foreach($products as $p){
  if($q!==''&&!str_contains(norm($p['name'].' '.$p['brand'].' '.$p['master_sku']),$q))continue;
  $s=stock_row($p['id']);$st=detect_status($s['current'],$p['low_stock_threshold']??10);
  if($status!==''&&stock_status_key($st[0])!==$status)continue;
  $rows[]=['product'=>$p,'stock'=>$s,'status'=>$st];
 }
 return $rows;
}
function cs_download_url(){return 'index.php?'.http_build_query(array_merge(['page'=>'stocks','download'=>'xlsx'],array_intersect_key($_GET,array_flip(['brand','main_category','subcategory','q','status']))));}
function cs_download_stocks($products){
 $path=null;$pdo=db();
 try{
  $pdo->beginTransaction();unset($GLOBALS['OM_RESERVED']);
  $rows=[];$totals=array_fill(0,7,0);
  foreach(cs_stock_rows($products,$_GET['q']??'',$_GET['status']??'') as $r){
   $p=$r['product'];$s=$r['stock'];$qty=array_map(fn($key)=>(int)$s[$key],['beginning','current','reserved','available','nonsellable','physical']);$qty[]=studio_balance($p['id']);
   foreach($qty as $i=>$v)$totals[$i]+=$v;
   $rows[]=array_merge([$p['master_sku'],$p['name'],inventory_filter_brand($p['brand']),$p['main_category']??'',$p['category']],$qty,[$r['status'][0]]);
  }
  $count=count($rows);$rows[]=array_merge(['','TOTAL','','',''],$totals,['']);
  $filters=[];foreach(['brand'=>'Brand','main_category'=>'Main Category','subcategory'=>'Subcategory','q'=>'Search','status'=>'Status'] as $key=>$label)if(($_GET[$key]??'')!=='')$filters[]=$label.': '.(string)$_GET[$key];
  $path=tempnam(sys_get_temp_dir(),'current-stocks-');if($path===false)throw new Exception('Cannot prepare the stock download.');
  report_write_xlsx($path,'Current Stocks',['Master SKU','Product Description','Brand','Main Category','Subcategory','Beginning Qty','Sellable On Hand Qty','Reserved Qty','Available Qty','Non-Sellable Qty','Total Physical Qty','Studio Qty (Included in Non-Sellable)','Status'],$rows,['As Of'=>date('Y-m-d H:i:s').' '.date('T'),'Generated By'=>current_user()['name'],'Filters'=>$filters?implode('; ',$filters):'All active products','Products'=>$count,'Quantity Unit'=>'pcs','Basis'=>'All matching active products. Available = Sellable On Hand - Reserved. Total Physical = Sellable On Hand + Non-Sellable. Reservations do not reduce physical quantity.']);
  $pdo->commit();header('Content-Type: application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');header('Content-Disposition: attachment; filename="Current_Stocks_'.date('Ymd_His').'.xlsx"');header('Cache-Control: private, no-store');header('X-Content-Type-Options: nosniff');readfile($path);
 }catch(Throwable $e){if($pdo->inTransaction())$pdo->rollBack();http_response_code(400);echo '<h1>Stock download unavailable</h1><p>'.e(safe_error_message($e)).'</p><a href="index.php?page=stocks">Back to Current Stocks</a>';}
 finally{if($path&&is_file($path))unlink($path);}
}
